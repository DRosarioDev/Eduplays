function hoBank(nouns) {
  return nouns.map((noun) => ({
    text: `Io ___ ${noun}.`,
    answer: "ho",
    other: "o",
  }));
}

function haiBank(nouns) {
  return nouns.map((noun) => ({
    text: `Tu ___ ${noun}.`,
    answer: "hai",
    other: "ai",
  }));
}

function haBank(items) {
  return items.map(({ subject, complement }) => ({
    text: `${subject} ___ ${complement}.`,
    answer: "ha",
    other: "a",
  }));
}

function hannoBank(nouns) {
  return nouns.map((noun) => ({
    text: `Loro ___ ${noun}.`,
    answer: "hanno",
    other: "anno",
  }));
}

function aBank(places) {
  return places.map((place) => ({
    text: `Vado ___ ${place}.`,
    answer: "a",
    other: "ha",
  }));
}

function aiBank(sentences) {
  return sentences.map((text) => ({ text, answer: "ai", other: "hai" }));
}

function annoBank(sentences) {
  return sentences.map((text) => ({ text, answer: "anno", other: "hanno" }));
}

function oBank(sentences) {
  return sentences.map((text) => ({ text, answer: "o", other: "ho" }));
}

