/** 0 = Base (2 sillabe), 1 = Facile (3), 2 = Medio (4 o più). */
export function syllableLevel(entry) {
  return Math.min(2, Math.max(0, entry.syllables.length - 2));
}

/**
 * Per il gioco delle sillabe usiamo il livello esatto: così la difficoltà
 * Facile non contiene più tutte le parole di Base e le domande non girano
 * sempre attorno agli stessi termini.
 */
export function filterWordsByDifficulty(items, difficulty) {
  return items.filter((entry) => syllableLevel(entry) === difficulty);
}

/** 0 = 4-5 lettere, 1 = 6-7 lettere, 2 = 8 o più lettere. */
export function missingLetterLevel(entry) {
  if (entry.word.length <= 5) return 0;
  if (entry.word.length <= 7) return 1;
  return 2;
}

export function filterWordsByMissingLevel(items, difficulty) {
  return items.filter((entry) => missingLetterLevel(entry) === difficulty);
}
